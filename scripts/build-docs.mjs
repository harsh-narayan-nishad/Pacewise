// Bundles docs/**/*.md into lib/docs/generated.ts so the public notes pages can show them without
// reading the file system at run time (works on Vercel). Only Markdown is included: docs/*.csv
// (demo account credentials) is deliberately left out.
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from "node:fs";
import { join, relative, basename, dirname, resolve, sep } from "node:path";

const root = join(process.cwd(), "docs");
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (name.endsWith(".md")) files.push(p);
  }
})(root);

/**
 * Code kept in its own file. A line `::include cpp/quick-sort.cpp` inside a doc is replaced, at build time, by a
 * code block holding that file (path shown as the title, colours and Copy button as usual). A `.out.txt` file
 * becomes an "Output" block. The path is relative to the doc and must stay inside docs/.
 */
const LANG = { cpp: "cpp", c: "c", h: "cpp", java: "java", ts: "ts", js: "js", py: "python", sh: "bash", json: "json", txt: "text" };
function expandIncludes(md, docPath) {
  return md.replace(/^[ \t]*::include[ \t]+(\S+)[ \t]*$/gm, (_, target) => {
    const file = resolve(dirname(docPath), target);
    if (!file.startsWith(root + sep) || !existsSync(file)) throw new Error(`${relative(root, docPath)}: ::include ${target} not found inside docs/`);
    const text = readFileSync(file, "utf8").replace(/\r\n?/g, "\n").replace(/\n+$/, "");
    const isOut = /\.out\.txt$/.test(file);
    const lang = isOut ? "text" : LANG[file.split(".").pop().toLowerCase()] ?? "text";
    const title = isOut ? "Output" : relative(dirname(docPath), file).split(sep).join("/");
    if (text.includes("```")) throw new Error(`${target}: contains a code fence`);
    return "```" + lang + ' title="' + title + '"\n' + text + "\n```";
  });
}

const docs = files.map((p) => {
  const rel = relative(root, p).split("\\").join("/");
  const md = expandIncludes(readFileSync(p, "utf8"), p);
  const folder = rel.includes("/") ? rel.split("/").slice(0, -1).join("/") : "";
  const title = (md.match(/^#\s+(.+)$/m)?.[1] ?? basename(rel, ".md")).replace(/[`*_]/g, "").trim();
  return { slug: rel.replace(/\.md$/, "").replace(/\//g, "--").toLowerCase(), path: rel, folder, title, md };
});

writeFileSync(
  join(process.cwd(), "lib/docs/generated.ts"),
  `// AUTO-GENERATED by scripts/build-docs.mjs from docs/**/*.md. Do not edit by hand.\n` +
    `export interface DocSource { slug: string; path: string; folder: string; title: string; md: string }\n` +
    `export const DOCS: DocSource[] = ${JSON.stringify(docs, null, 1)};\n`
);
// Titles only, safe to import from client components (the menu) without shipping every document.
writeFileSync(
  join(process.cwd(), "lib/docs/index.generated.ts"),
  `// AUTO-GENERATED by scripts/build-docs.mjs. Do not edit by hand.\n` +
    `export interface DocMeta { slug: string; path: string; folder: string; title: string }\n` +
    `export const DOC_INDEX: DocMeta[] = ${JSON.stringify(docs.map(({ md, ...meta }) => meta), null, 1)};\n`
);
// Full-text search index: one entry per section (heading + plain text), loaded on demand by the navbar search.
const slugify = (t) => t.toLowerCase().replace(/<[^>]+>/g, "").replace(/[`*_~]/g, "").replace(/[^a-z0-9\s-]/g, "").trim().replace(/\s+/g, "-");
const plain = (t) =>
  t
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/[`*_~=]{1,3}/g, "")
    .replace(/\|/g, " ")
    .replace(/^[>\s-]+/gm, "")
    .replace(/\s+/g, " ")
    .trim();
const entries = [];
for (const d of docs) {
  let heading = d.title, id = "", buf = [], fence = false;
  const flush = () => {
    const text = plain(buf.join("\n"));
    if (text || heading) entries.push({ slug: d.slug, title: d.title, folder: d.folder, heading, id, text });
    buf = [];
  };
  for (const line of d.md.split(/\r?\n/)) {
    if (/^\s*```/.test(line)) { fence = !fence; continue; }
    const h = !fence && line.match(/^(#{1,6})\s+(.*?)\s*#*\s*$/);
    if (h) {
      flush();
      heading = plain(h[2]);
      id = h[1].length >= 2 ? slugify(h[2]) : "";
    } else buf.push(line);
  }
  flush();
}
writeFileSync(
  join(process.cwd(), "lib/docs/search.generated.ts"),
  `// AUTO-GENERATED by scripts/build-docs.mjs. Do not edit by hand.\n` +
    `export interface SearchEntry { slug: string; title: string; folder: string; heading: string; id: string; text: string }\n` +
    `export const SEARCH_INDEX: SearchEntry[] = ${JSON.stringify(entries)};\n`
);
console.log(`docs: bundled ${docs.length} markdown files`);
