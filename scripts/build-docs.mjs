// Bundles docs/**/*.md into lib/docs/generated.ts so the public notes pages can show them without
// reading the file system at run time (works on Vercel). Only Markdown is included: docs/*.csv
// (demo account credentials) is deliberately left out.
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative, basename } from "node:path";

const root = join(process.cwd(), "docs");
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (name.endsWith(".md")) files.push(p);
  }
})(root);

const docs = files.map((p) => {
  const rel = relative(root, p).split("\\").join("/");
  const md = readFileSync(p, "utf8");
  const folder = rel.includes("/") ? rel.split("/").slice(0, -1).join("/") : "";
  const title = (md.match(/^#\s+(.+)$/m)?.[1] ?? basename(rel, ".md")).replace(/[`*_]/g, "").trim();
  return { slug: rel.replace(/\.md$/, "").replace(/\//g, "--").toLowerCase(), path: rel, folder, title, md };
});

writeFileSync(
  join(process.cwd(), "lib/docs/generated.ts"),
  `// AUTO-GENERATED by scripts/build-docs.mjs from docs/**/*.md. Do not edit by hand.\n` +
    `export interface DocSource { slug: string; path: string; folder: string; title: string; md: string }\n` +
    `export const DOCS: DocSource[] = ${JSON.stringify(docs, null, 1)};\n`
);
// Titles only, safe to import from client components (the menu) without shipping every document.
writeFileSync(
  join(process.cwd(), "lib/docs/index.generated.ts"),
  `// AUTO-GENERATED by scripts/build-docs.mjs. Do not edit by hand.\n` +
    `export interface DocMeta { slug: string; path: string; folder: string; title: string }\n` +
    `export const DOC_INDEX: DocMeta[] = ${JSON.stringify(docs.map(({ md, ...meta }) => meta), null, 1)};\n`
);
console.log(`docs: bundled ${docs.length} markdown files`);
